// City Notes layout proposal (CN-1 boards): turns the verbatim destination sheet into the data the
// static frames show. Design evidence only; the product reader is proposed in the spec (§6) and
// not built. Run from the repository root: node docs/design/city-notes/scripts/build-data.mjs
// Names are never edited. Locations follow the spec's rules L1–L4; every value keeps its cell.
import { writeFileSync } from "node:fs";
import { NEARBY_SHEET } from "../../../../src/content/vnest-workbook/details.ts";

const SHEET = "Thông tin các điểm tham quan";
// Cells with an open data question (Q32): the street part is not shown, only the area (rule L4).
const DEFECTS = { D30: "“Trần phú”: casing (Q32)", D33: "“!0”: probably “10” (Q32)" };
const NAME_FLAGS = { C13: "“Huynh Hoa”: spelling to confirm, shown as written (Q32)" };
const CITY_OF = { "Hồ Chí Minh": { id: "ho-chi-minh", label: "TP. Hồ Chí Minh" }, "Đà Nẵng": { id: "da-nang", label: "Đà Nẵng" } };

const tidy = (s) => s.trim().replace(/,(?=\S)/g, ", ").replace(/\s{2,}/g, " "); // L1
function location(raw, cell) {
  const parts = tidy(raw).split(", ");
  const city = parts.at(-1);
  let shown = parts.slice(0, -1); // L2: the city is the note's own heading
  let rule = "L1 L2";
  if (DEFECTS[cell]) {
    shown = shown.slice(1); // L4: drop the street part that holds the defect
    rule += " L4";
  }
  if (shown.length === 0) shown = parts; // never empty
  return { raw, display: shown.join(", "), full: tidy(raw), city, cell, status: rule === "L1 L2" && tidy(raw) === raw ? "derived" : "normalized", rule, flag: DEFECTS[cell] };
}

const heads = NEARBY_SHEET.filter((r) => r.A?.startsWith("Khu vực các cơ sở:"));
const notes = heads.map((head, i) => {
  const end = heads[i + 1]?.row ?? Infinity;
  const rows = NEARBY_SHEET.filter((r) => r.row > head.row && r.row < end && (r.B || r.C) && r.A !== "STT");
  const places = rows.map((r) => {
    const col = r.B ? "B" : "C";
    const rawName = r.B ?? r.C;
    return { row: r.row, category: r.B ? "explore" : "eat", name: { raw: rawName, display: rawName.trim(), cell: `${col}${r.row}`, flag: NAME_FLAGS[`${col}${r.row}`] }, location: location(r.D, `D${r.row}`) };
  });
  const cities = [...new Set(places.map((p) => p.location.city))];
  if (cities.length !== 1 || !CITY_OF[cities[0]]) throw new Error(`Block A${head.row}: expected one known city, got ${cities}`);
  return {
    city: CITY_OF[cities[0]],
    header: { raw: head.A, cell: `A${head.row}`, serves: head.A.replace("Khu vực các cơ sở:", "").split(",").map((s) => s.trim()) },
    eat: places.filter((p) => p.category === "eat"),
    explore: places.filter((p) => p.category === "explore"),
  };
});

const out = new URL("../frames/data.js", import.meta.url);
writeFileSync(out, `// GENERATED by scripts/build-data.mjs from src/content/vnest-workbook/details.ts (sheet "${SHEET}"). Do not edit.\nwindow.CITY_NOTES = ${JSON.stringify(notes, null, 1)};\n`);
for (const n of notes) console.log(n.city.label, "eat", n.eat.length, "explore", n.explore.length, "serves", n.header.serves.join(" / "));
for (const n of notes) for (const p of [...n.eat, ...n.explore]) console.log(`${p.name.cell.padEnd(4)} ${p.name.display.padEnd(55)} → ${p.location.display}  [${p.location.status} ${p.location.rule}]`);
